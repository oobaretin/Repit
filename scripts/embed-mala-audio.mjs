#!/usr/bin/env node
/** Embeds public/sounds/mala.mp3 as base64 for offline Web Audio decode (no fetch on iOS). */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'public/sounds/mala.mp3');
const out = join(root, 'constants/malaAudioData.ts');

const base64 = readFileSync(src).toString('base64');
writeFileSync(
  out,
  `/** Auto-generated by scripts/embed-mala-audio.mjs — original Mixkit bead click. */\nexport const MALA_MP3_BASE64 = '${base64}';\n`,
);
console.log(`Embedded mala.mp3 (${base64.length} base64 chars) → constants/malaAudioData.ts`);
